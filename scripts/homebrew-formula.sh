#!/usr/bin/env bash
# Print the Homebrew formula for a release.
#
#   scripts/homebrew-formula.sh TAG CHECKSUM_DIR > Formula/rushdb.rb
#
# CHECKSUM_DIR holds the release's rushdb-<target>.tar.gz.sha256 files.
set -euo pipefail

TAG="${1:?usage: homebrew-formula.sh TAG CHECKSUM_DIR}"
DIR="${2:?usage: homebrew-formula.sh TAG CHECKSUM_DIR}"
REPO="${RUSHDB_REPO:-rush-db/rushdb}"
VERSION="${TAG#v}"

sha() {
  local file="$DIR/rushdb-$1.tar.gz.sha256"
  [ -f "$file" ] || { echo "missing $file" >&2; exit 1; }
  awk '{print $1}' "$file"
}

asset() {
  printf '      url "https://github.com/%s/releases/download/%s/rushdb-%s.tar.gz"\n' "$REPO" "$TAG" "$1"
  printf '      sha256 "%s"\n' "$(sha "$1")"
}

cat <<EOF
# Generated by scripts/homebrew-formula.sh for $TAG; do not edit by hand.
class Rushdb < Formula
  desc "Property graph database with SQL, vector search and full-text search"
  homepage "https://github.com/$REPO"
  version "$VERSION"
  license "Apache-2.0"

  on_macos do
    on_arm do
$(asset aarch64-apple-darwin)
    end
    on_intel do
$(asset x86_64-apple-darwin)
    end
  end

  on_linux do
    on_arm do
$(asset aarch64-unknown-linux-gnu)
    end
    on_intel do
$(asset x86_64-unknown-linux-gnu)
    end
  end

  def install
    bin.install "rushdb"
  end

  def post_install
    (var/"rushdb").mkpath
  end

  service do
    run [opt_bin/"rushdb", "serve", "--data-dir", var/"rushdb"]
    keep_alive true
    working_dir var
    log_path var/"log/rushdb.log"
    error_log_path var/"log/rushdb.log"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/rushdb --version")
    port = free_port
    pid = spawn bin/"rushdb", "serve", "--data-dir", testpath/"data", "--port", port.to_s, "--pgwire-port", "0"
    begin
      sleep 3
      assert_match "ok", shell_output("#{bin}/rushdb health --url http://127.0.0.1:#{port}")
    ensure
      Process.kill("TERM", pid)
      Process.wait(pid)
    end
  end
end
EOF
